def render(a):
    L = ["---", f"name: {a['name']}", f"description: {a['desc']}", f"tools: {a['tools']}", "---", "",
         f"# {a['title']}", "", a["role"], ""]
    if a["jobs"]:
        L += ["兼ねる職種：" + "、".join(a["jobs"]), ""]
    L += ["## 最初に読むもの", "",
         "- プロデューサー（メインのClaude）が渡した、プロジェクトのフォルダと、その仕事のファイル",
         "- プロジェクトの `進行表.md` と `開発チーム.md`（あれば）"]
    for x in a.get("extra_read", []):
        L.append(f"- {x}")
    if a["core"]:
        L.append(f"- スキル `game_dev_studio_jp` の `SKILL.md` と、部門の参考ファイル `ゲーム/.claude/skills/game_dev_studio_jp/reference/{DEPT[a['dept']]}`")
    else:
        L.append("- スキル `game_dev_studio_jp` の `SKILL.md` と、プロデューサーが伝えた「いまの部門」の参考ファイル（`ゲーム/.claude/skills/game_dev_studio_jp/reference/`）")
        L.append("- いまの部門の、前の部門までに作られた資料のうち、自分の仕事に関係するもの")
    L += ["", COMMON_NOTE, ""]
    if not a["core"]:
        L += ["## 参加する部門", ""]
        for p, t in a["phases"].items():
            L.append(f"- **{p} {PHASE_NAME[p]}**：{t}")
        L.append("")
    L += ["## 仕事", ""]
    L += [f"- {x}" for x in a["work"]]
    L.append("")
    L += ["## この職種のトップがすること", ""]
    for x in ROLE[a["name"]]:
        if a["name"] == "game-beta-firsttime" and x.startswith("「直し方」"):
            x += "（下の共通の「直し方まで出す」「目的から見る」は、この役ではしない。作り手の目的を知らない目で見ることが、この役の価値）"
        L.append(f"- {x}")
    L.append("")
    L += (COMMON_MAKER if a["kind"] == "make" else COMMON_REVIEWER).split("\n")
    if a["kind"] == "make":
        L += ["## 終えたら", "",
              "- 自分で一度見直す。動くものは実際に動かして確かめる（確かめられなかったら、そう書く）",
              "- プロデューサーに返す：この仕事の目的（1行）、書いた・変えたファイルのパス、自分で決めたことと理由、決めずに残したこと（未決）、気になっているところ（悪い知らせは先頭に）、頼まれていないが要る提案（あれば、分けて）",
              "- 自分の役割の範囲をこえる変更（仕様、デザイン、ほかの担当のファイル）は、勝手にせず返す",
              "- `開発チーム.md` で自分に足された観点があれば、それも守る"]
    else:
        L += ["## 返し方", ""]
        if a["name"] == "game-beta-firsttime":
            L.append("- 先頭に、いちばん困った・やめたくなった所を3つまで挙げる")
        else:
            L.append("- 先頭に、いちばん効く直しを3つまで挙げる（全体を読まなくても、次の作業が決められるように）")
        if "Write" not in a["tools"]:
            L.append("- ファイルは書き換えない")
        if "ret" in a:
            L += [f"- {x}" for x in a["ret"]]
        else:
            L += ["- 指摘ごとに：場所（ファイルと行、見出し、画面）、該当のもの（そのまま引用）、何が問題か、直し案（そのまま差し替えられる形）",
                  "- 重さを付ける：**必ず直す**（作れない、矛盾、壊れる、柱からずれる）／**直したほうがいい**（もっとよくなる）"]
        L += ["- 事実と推測を分ける。確かめていないことは「確かめていない」と書く",
              "- 自分の役割の範囲に絞る。問題がなければ「なし」と返す",
              "- 直すと壊れる良いところは「残す」として挙げる",
              "- `開発チーム.md` で自分に足された観点があれば、それも見る"]
    return "\n".join(L) + "\n"

